USER_INDEXES = [
    """CREATE UNIQUE INDEX IF NOT EXISTS ux_users_uuid ON users(uuid) WHERE uuid <> ''""",
    """CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email ON users(email) WHERE email <> ''""",
]

USER_NEW_COLUMNS = [
    ("nickname", "TEXT NOT NULL DEFAULT ''"),
    ("uuid", "TEXT NOT NULL DEFAULT ''"),
    ("avatar", "TEXT NOT NULL DEFAULT ''"),
    ("bio", "TEXT NOT NULL DEFAULT ''"),
    ("email", "TEXT NOT NULL DEFAULT ''"),
    ("emailverified", "INTEGER NOT NULL DEFAULT 0"),
]

RECOMMEND_EVENT_NEW_COLUMNS = [
    ("eventid", "TEXT NOT NULL DEFAULT ''"),
]


def tables_for(backend: str) -> list:
    return PG_TABLES if backend == "pg" else TABLES


def ensure_users() -> None:
    """老库 users 缺新列时补列(幂等), 补完再建部分唯一索引; 老行 uuid/email 为空不参与唯一性"""
    if db.storage_backend() == "pg":
        rows = db.query(
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND table_name = 'users'")
        have = {r["column_name"] for r in rows}
    else:
        have = {r["name"] for r in db.query("PRAGMA table_info(users)")}
    for name, ddl in USER_NEW_COLUMNS:
        if name not in have:
            db.run(f"ALTER TABLE users ADD COLUMN {name} {ddl}")
    for ddl in USER_INDEXES:
        db.run(ddl)


def ensure_recommend_events() -> None:
    if db.storage_backend() == "pg":
        rows = db.query(
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND table_name = 'recommend_events'")
        have = {r["column_name"] for r in rows}
    else:
        have = {r["name"] for r in db.query("PRAGMA table_info(recommend_events)")}
    for name, ddl in RECOMMEND_EVENT_NEW_COLUMNS:
        if name not in have:
            db.run(f"ALTER TABLE recommend_events ADD COLUMN {name} {ddl}")
    db.run("CREATE UNIQUE INDEX IF NOT EXISTS ux_recommend_events_user_eventid ON recommend_events(userid, eventid) WHERE eventid <> ''")


def main() -> None:
    db.connect(cfg.DATABASE_PATH)
    for ddl in tables_for(db.storage_backend()):
        db.run(ddl)
    ensure_users()
    ensure_recommend_events()
    db.close()
